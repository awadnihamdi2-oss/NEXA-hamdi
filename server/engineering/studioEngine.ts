import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { getDb, nowIso, recordAuditEvent } from '../db/database.ts';
import { assertPathInsideRoot } from '../security/auth.ts';

const execFileAsync = promisify(execFile);
const WORKSPACE_ROOT = path.resolve(process.cwd(), 'workspace_projects');

export interface EngineeringFile {
  path: string;
  content: string;
}

export type ProjectStack = 'node_ts_service' | 'python_quant_script' | 'static_web_app';

function buildTemplateFiles(name: string, objective: string, stack: ProjectStack): EngineeringFile[] {
  if (stack === 'python_quant_script') {
    return [
      {
        path: 'README.md',
        content: `# ${name}\n\nGenerated by NEXA Autonomous Software Engineering Studio.\n\nObjective: ${objective}\n`,
      },
      {
        path: 'main.py',
        content: `import json\n\ndef compute_moving_average(values, period=3):\n    if len(values) < period or period <= 0:\n        raise ValueError("Invalid period or insufficient values")\n    return [round(sum(values[i - period + 1:i + 1]) / period, 4) for i in range(period - 1, len(values))]\n\nif __name__ == "__main__":\n    sample = [100.0, 102.0, 101.5, 104.0, 106.0]\n    print(json.dumps({"project": "${name}", "ma3": compute_moving_average(sample, 3)}))\n`,
      },
      {
        path: 'test_main.py',
        content: `import unittest\nfrom main import compute_moving_average\n\nclass TestQuantScript(unittest.TestCase):\n    def test_moving_average(self):\n        res = compute_moving_average([10, 20, 30, 40], 2)\n        self.assertEqual(res, [15.0, 25.0, 35.0])\n\nif __name__ == "__main__":\n    unittest.main()\n`,
      },
    ];
  }

  if (stack === 'static_web_app') {
    return [
      {
        path: 'index.html',
        content: `<!doctype html>\n<html lang="en">\n<head><meta charset="utf-8" /><title>${name}</title></head>\n<body style="font-family:sans-serif;background:#0b0e14;color:#f8fafc;padding:32px;">\n  <h1>${name}</h1>\n  <p>${objective}</p>\n  <script src="./app.js"></script>\n</body>\n</html>\n`,
      },
      {
        path: 'app.js',
        content: `export function formatStatus(label) {\n  return String(label || 'READY').trim().toUpperCase();\n}\n`,
      },
      {
        path: 'app.test.mjs',
        content: `import assert from 'node:assert/strict';\nimport { formatStatus } from './app.js';\nassert.equal(formatStatus('active'), 'ACTIVE');\nconsole.log('ALL_TESTS_PASSED');\n`,
      },
    ];
  }

  // Default: node_ts_service (pure ESM JS so node --check & node test execute cleanly with zero extra build step)
  return [
    {
      path: 'README.md',
      content: `# ${name}\n\nGenerated by NEXA Software Engineering Studio.\n\nObjective: ${objective}\n`,
    },
    {
      path: 'index.mjs',
      content: `export function evaluateObjective(input) {\n  const text = String(input || '').trim();\n  if (!text) throw new Error('Input cannot be empty');\n  return { ok: true, length: text.length, normalized: text.toLowerCase() };\n}\n`,
    },
    {
      path: 'index.test.mjs',
      content: `import assert from 'node:assert/strict';\nimport { evaluateObjective } from './index.mjs';\n\nconst out = evaluateObjective('${name.replace(/'/g, '')}');\nassert.equal(out.ok, true);\nassert.ok(out.length > 0);\nconsole.log('TEST_SUITE_PASSED');\n`,
    },
  ];
}

export function createEngineeringProject(params: {
  name: string;
  objective: string;
  stack?: ProjectStack;
  files?: EngineeringFile[];
}) {
  const name = params.name.trim();
  const objective = params.objective.trim();
  if (name.length < 2 || objective.length < 5) {
    throw new Error('Project name and objective are required.');
  }

  const stack: ProjectStack = params.stack || 'node_ts_service';
  const id = `eng_${crypto.randomUUID().slice(0, 10)}`;
  const relDir = `${name.toLowerCase().replace(/[^a-z0-9]+/g, '_')}_${id}`;
  const projectDir = assertPathInsideRoot(WORKSPACE_ROOT, relDir);
  fs.mkdirSync(projectDir, { recursive: true });

  const files = params.files && params.files.length > 0 ? params.files : buildTemplateFiles(name, objective, stack);
  for (const f of files) {
    const absFile = assertPathInsideRoot(projectDir, f.path);
    fs.mkdirSync(path.dirname(absFile), { recursive: true });
    fs.writeFileSync(absFile, f.content, 'utf-8');
  }

  const ts = nowIso();
  getDb()
    .prepare(
      `INSERT INTO engineering_projects
       (id, name, stack, objective, workspace_rel_path, status, files_json, last_build_log, last_test_status, created_at, updated_at)
       VALUES (?, ?, ?, ?, ?, 'CREATED', ?, 'Scaffolded project in isolated sandbox.', 'NOT_RUN', ?, ?)`
    )
    .run(id, name, stack, objective, relDir, JSON.stringify(files), ts, ts);

  createProjectSnapshot(id, 'initial_scaffold');
  recordAuditEvent('operator', 'ENGINEERING', 'PROJECT_CREATED', { id, name, stack });
  return getEngineeringProject(id)!;
}

export function updateProjectFile(projectId: string, filePath: string, content: string) {
  const proj = getEngineeringProject(projectId);
  if (!proj) throw new Error('Engineering project not found.');

  const projectDir = assertPathInsideRoot(WORKSPACE_ROOT, proj.workspaceRelPath);
  const absFile = assertPathInsideRoot(projectDir, filePath);
  fs.mkdirSync(path.dirname(absFile), { recursive: true });
  fs.writeFileSync(absFile, content, 'utf-8');

  const files = [...proj.files];
  const idx = files.findIndex((f) => f.path === filePath);
  if (idx >= 0) files[idx] = { path: filePath, content };
  else files.push({ path: filePath, content });

  getDb()
    .prepare('UPDATE engineering_projects SET files_json = ?, updated_at = ? WHERE id = ?')
    .run(JSON.stringify(files), nowIso(), projectId);

  return getEngineeringProject(projectId)!;
}

export function createProjectSnapshot(projectId: string, label: string) {
  const proj = getEngineeringProject(projectId);
  if (!proj) throw new Error('Engineering project not found.');
  const serialized = JSON.stringify(proj.files);
  const sha256 = crypto.createHash('sha256').update(serialized).digest('hex');
  const snapId = `snp_${crypto.randomUUID().slice(0, 10)}`;
  getDb()
    .prepare('INSERT INTO engineering_snapshots (id, project_id, label, files_json, sha256, created_at) VALUES (?, ?, ?, ?, ?, ?)')
    .run(snapId, projectId, label, serialized, sha256, nowIso());
  return { id: snapId, label, sha256 };
}

export function rollbackProjectSnapshot(projectId: string, snapshotId: string) {
  const proj = getEngineeringProject(projectId);
  if (!proj) throw new Error('Engineering project not found.');
  const snap = getDb()
    .prepare('SELECT * FROM engineering_snapshots WHERE id = ? AND project_id = ?')
    .get(snapshotId, projectId) as Record<string, unknown> | undefined;
  if (!snap) throw new Error('Snapshot not found.');

  const files = JSON.parse(String(snap.files_json)) as EngineeringFile[];
  const projectDir = assertPathInsideRoot(WORKSPACE_ROOT, proj.workspaceRelPath);
  for (const f of files) {
    const absFile = assertPathInsideRoot(projectDir, f.path);
    fs.mkdirSync(path.dirname(absFile), { recursive: true });
    fs.writeFileSync(absFile, f.content, 'utf-8');
  }

  getDb()
    .prepare('UPDATE engineering_projects SET files_json = ?, last_build_log = ?, updated_at = ? WHERE id = ?')
    .run(JSON.stringify(files), `Rolled back cleanly to snapshot ${snapshotId} (${String(snap.label)}).`, nowIso(), projectId);

  recordAuditEvent('operator', 'ENGINEERING', 'PROJECT_ROLLBACK', { projectId, snapshotId });
  return getEngineeringProject(projectId)!;
}

export async function runProjectValidationAndTests(projectId: string) {
  const proj = getEngineeringProject(projectId);
  if (!proj) throw new Error('Engineering project not found.');
  const projectDir = assertPathInsideRoot(WORKSPACE_ROOT, proj.workspaceRelPath);

  const started = Date.now();
  const logs: string[] = [];
  let passed = 0;
  let failed = 0;

  for (const f of proj.files) {
    const abs = assertPathInsideRoot(projectDir, f.path);
    if (f.path.endsWith('.mjs') || f.path.endsWith('.js')) {
      try {
        await execFileAsync('node', ['--check', abs], { cwd: projectDir, timeout: 8000 });
        logs.push(`SYNTAX PASS: ${f.path}`);
        passed++;
      } catch (err) {
        const msg = err instanceof Error ? err.message : 'Syntax error';
        logs.push(`SYNTAX FAIL (${f.path}): ${msg}`);
        failed++;
      }
    } else if (f.path.endsWith('.py')) {
      try {
        await execFileAsync('python3', ['-m', 'py_compile', abs], { cwd: projectDir, timeout: 8000 });
        logs.push(`PY_COMPILE PASS: ${f.path}`);
        passed++;
      } catch (err) {
        const msg = err instanceof Error ? err.message : 'Python compile error';
        logs.push(`PY_COMPILE FAIL (${f.path}): ${msg}`);
        failed++;
      }
    }
  }

  // Run isolated test file (allowlisted filenames only)
  const jsTest = proj.files.find((f) => f.path.endsWith('.test.mjs'));
  const pyTest = proj.files.find((f) => f.path.startsWith('test_') && f.path.endsWith('.py'));

  if (jsTest) {
    try {
      const { stdout } = await execFileAsync('node', [assertPathInsideRoot(projectDir, jsTest.path)], {
        cwd: projectDir,
        timeout: 8000,
      });
      logs.push(`TEST RUN PASS (${jsTest.path}): ${stdout.trim()}`);
      passed++;
    } catch (err) {
      const msg = err instanceof Error ? err.message : 'Test failed';
      logs.push(`TEST RUN FAIL (${jsTest.path}): ${msg}`);
      failed++;
    }
  } else if (pyTest) {
    try {
      const { stdout, stderr } = await execFileAsync('python3', [assertPathInsideRoot(projectDir, pyTest.path)], {
        cwd: projectDir,
        timeout: 8000,
      });
      logs.push(`PY UNITTEST PASS (${pyTest.path}): ${(stdout || stderr).trim()}`);
      passed++;
    } catch (err) {
      const msg = err instanceof Error ? err.message : 'Python test failed';
      logs.push(`PY UNITTEST FAIL (${pyTest.path}): ${msg}`);
      failed++;
    }
  }

  const durationMs = Date.now() - started;
  const total = passed + failed;
  const testStatus = failed === 0 && total > 0 ? 'PASSED' : 'FAILED';
  const output = logs.join('\n');

  const runId = `tst_${crypto.randomUUID().slice(0, 10)}`;
  getDb()
    .prepare('INSERT INTO test_runs (id, project_id, suite, passed, failed, total, output, duration_ms, created_at) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)')
    .run(runId, projectId, proj.stack, passed, failed, total, output, durationMs, nowIso());

  getDb()
    .prepare('UPDATE engineering_projects SET status = ?, last_build_log = ?, last_test_status = ?, updated_at = ? WHERE id = ?')
    .run(testStatus === 'PASSED' ? 'VERIFIED' : 'NEEDS_REPAIR', output, testStatus, nowIso(), projectId);

  recordAuditEvent('operator', 'ENGINEERING', 'PROJECT_TESTED', { projectId, testStatus, passed, failed });
  return { runId, testStatus, passed, failed, total, durationMs, output, project: getEngineeringProject(projectId)! };
}

export function listEngineeringProjects() {
  const rows = getDb().prepare('SELECT * FROM engineering_projects ORDER BY updated_at DESC LIMIT 30').all() as Array<
    Record<string, unknown>
  >;
  return rows.map((r) => ({
    id: String(r.id),
    name: String(r.name),
    stack: r.stack as ProjectStack,
    objective: String(r.objective),
    workspaceRelPath: String(r.workspace_rel_path),
    status: String(r.status),
    files: JSON.parse(String(r.files_json)) as EngineeringFile[],
    lastBuildLog: r.last_build_log ? String(r.last_build_log) : '',
    lastTestStatus: r.last_test_status ? String(r.last_test_status) : 'NOT_RUN',
    createdAt: String(r.created_at),
    updatedAt: String(r.updated_at),
  }));
}

export function getEngineeringProject(id: string) {
  const proj = listEngineeringProjects().find((p) => p.id === id) || null;
  if (!proj) return null;
  const snapshots = getDb()
    .prepare('SELECT id, label, sha256, created_at FROM engineering_snapshots WHERE project_id = ? ORDER BY created_at DESC')
    .all(id);
  const testRuns = getDb()
    .prepare('SELECT * FROM test_runs WHERE project_id = ? ORDER BY created_at DESC LIMIT 10')
    .all(id);
  return { ...proj, snapshots, testRuns };
}
